// Regenerates src/generated.js and src/generated.d.ts from the mini-app
// contracts. Run: node scripts/generate.mjs

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const contractsDir = path.join(packageRoot, "..", "..", "contracts", "domains", "miniapps");
const outputJs = path.join(packageRoot, "src", "generated.js");
const outputTypes = path.join(packageRoot, "src", "generated.d.ts");

async function readContract(file) {
  return JSON.parse(await readFile(path.join(contractsDir, file), "utf8"));
}

const [host, catalog, pkg] = await Promise.all([
  readContract("mini-host.v1.json"),
  readContract("mini-catalog.v1.json"),
  readContract("mini-package.v1.json"),
]);

if (!Array.isArray(host.oneOf) || host.oneOf.length === 0) {
  throw new Error("mini-host contract has no oneOf branches");
}

const versionOf = (contract, file) => {
  const version = contract["x-contract-version"];
  if (!version) {
    throw new Error(`${file} has no x-contract-version`);
  }
  return version;
};

const camelCase = (method) =>
  method.replace(/[.-](\w)/g, (_, letter) => letter.toUpperCase());

const methods = new Map();
const scopes = new Map();
for (const branch of host.oneOf) {
  const method = branch.title;
  const scope = branch["x-scope"];
  if (!method || !scope) {
    throw new Error("every branch needs a title and x-scope");
  }
  const key = camelCase(method);
  if (methods.has(key)) {
    throw new Error(`duplicate method key ${key}`);
  }
  methods.set(key, method);
  scopes.set(method, scope);
}

const quote = (value) => JSON.stringify(value);
const versions = {
  host: versionOf(host, "mini-host.v1.json"),
  catalog: versionOf(catalog, "mini-catalog.v1.json"),
  package: versionOf(pkg, "mini-package.v1.json"),
};

const js = [
  "// Generated by scripts/generate.mjs from contracts/domains/miniapps.",
  "// Do not edit by hand.",
  "",
  `export const CONTRACT_VERSION = ${quote(versions.host)};`,
  "export const CONTRACT_VERSIONS = Object.freeze({",
  ...Object.entries(versions).map(([key, value]) => `  ${key}: ${quote(value)},`),
  "});",
  `export const REQUEST_ID_PATTERN = /${host["x-request-id-pattern"]}/;`,
  "",
  "export const METHODS = Object.freeze({",
  ...[...methods].map(([key, method]) => `  ${key}: ${quote(method)},`),
  "});",
  "",
  "export const SCOPES = Object.freeze({",
  ...[...scopes].map(([method, scope]) => `  ${quote(method)}: ${quote(scope)},`),
  "});",
  "",
  "export const ERROR_CODES = Object.freeze([",
  ...host["x-errors"].map((code) => `  ${quote(code)},`),
  "]);",
  "",
];

const literal = (value) => quote(value);
const dts = [
  "// Generated by scripts/generate.mjs. Do not edit by hand.",
  "",
  `export declare const CONTRACT_VERSION: ${literal(versions.host)};`,
  "export declare const CONTRACT_VERSIONS: Readonly<{",
  ...Object.entries(versions).map(([key, value]) => `  ${key}: ${literal(value)};`),
  "}>;",
  "export declare const REQUEST_ID_PATTERN: RegExp;",
  "",
  "export type Method =",
  ...[...methods.values()].map((method) => `  | ${literal(method)}`),
  ";",
  "",
  "export type Scope =",
  ...[...new Set(scopes.values())].map((scope) => `  | ${literal(scope)}`),
  ";",
  "",
  "export type ErrorCode =",
  ...host["x-errors"].map((code) => `  | ${literal(code)}`),
  ";",
  "",
  "export declare const METHODS: Readonly<{",
  ...[...methods].map(([key, method]) => `  ${key}: ${literal(method)};`),
  "}>;",
  "export declare const SCOPES: Readonly<Record<Method, Scope>>;",
  "export declare const ERROR_CODES: readonly ErrorCode[];",
  "",
];

await writeFile(outputJs, js.join("\n"), "utf8");
await writeFile(outputTypes, dts.join("\n"), "utf8");
console.log(`wrote ${outputJs} and ${outputTypes} (${methods.size} methods)`);
