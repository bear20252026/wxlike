// Regenerates src/generated.js from the mini-host.v1 contract.
// Run: node scripts/generate.mjs

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const contractPath = path.join(
  packageRoot,
  "..",
  "..",
  "contracts",
  "domains",
  "miniapps",
  "mini-host.v1.json",
);
const outputPath = path.join(packageRoot, "src", "generated.js");

const contract = JSON.parse(await readFile(contractPath, "utf8"));
if (!Array.isArray(contract.oneOf) || contract.oneOf.length === 0) {
  throw new Error("contract has no oneOf branches");
}

const camelCase = (method) =>
  method.replace(/[.-](\w)/g, (_, letter) => letter.toUpperCase());

const methods = new Map();
const scopes = new Map();
for (const branch of contract.oneOf) {
  const method = branch.title;
  const scope = branch["x-scope"];
  if (!method || !scope) {
    throw new Error("every branch needs a title and x-scope");
  }
  const key = camelCase(method);
  if (methods.has(key)) {
    throw new Error(`duplicate method key ${key}`);
  }
  methods.set(key, method);
  scopes.set(method, scope);
}

const quote = (value) => JSON.stringify(value);
const lines = [
  "// Generated by scripts/generate.mjs from",
  "// contracts/domains/miniapps/mini-host.v1.json. Do not edit by hand.",
  "",
  `export const CONTRACT_VERSION = ${quote(contract["x-contract-version"])};`,
  `export const REQUEST_ID_PATTERN = /${contract["x-request-id-pattern"]}/;`,
  "",
  "export const METHODS = Object.freeze({",
  ...[...methods].map(([key, method]) => `  ${key}: ${quote(method)},`),
  "});",
  "",
  "export const SCOPES = Object.freeze({",
  ...[...scopes].map(([method, scope]) => `  ${quote(method)}: ${quote(scope)},`),
  "});",
  "",
  "export const ERROR_CODES = Object.freeze([",
  ...contract["x-errors"].map((code) => `  ${quote(code)},`),
  "]);",
  "",
];

await writeFile(outputPath, lines.join("\n"), "utf8");
console.log(`wrote ${outputPath} (${methods.size} methods)`);
