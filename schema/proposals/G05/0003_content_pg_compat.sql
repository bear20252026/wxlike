-- M014 — 平台内容/工单 PG 兼容层（PostgreSQL）
--
-- 目的：给 G00-04 的旧 repo 切 PG 提供同名兼容表。第一批是 `reports`（举报
-- 工单）、`content_index` / `content_media_refs`（G05 公开内容索引与媒体引用）；
-- 第二批是本文件后半的 63 张平台旧表（好友/群/社群/钱包/朋友圈/设备/收藏/
-- 内容/状态等），供已切通用端口的 26 个旧 repo 直接执行原 SQL。
--
-- 列序与 SQLite 侧 M001/M005/M008 对齐，`INTEGER` → `BIGINT`、
-- `AUTOINCREMENT` → identity、`BLOB` → `BYTEA`，SQLite-only `REFERENCES` 省略；
-- 外键留给最终模型。users/sessions 用 M011 视图、media 用 M012 视图，不在这里重复。
--
-- expand-only：只建表和索引，不改既有对象。全部 IF NOT EXISTS，可重入。
-- 回滚：DROP TABLE content_media_refs / content_index / reports 以及本文件后半
-- 的 63 张平台旧表（只回收本迁移新建的投影，不影响 identity/media/ledger 表）。

BEGIN;

CREATE TABLE IF NOT EXISTS reports (
    id           TEXT PRIMARY KEY,
    reporter     TEXT NOT NULL,
    target_kind  TEXT NOT NULL,
    target_id    TEXT NOT NULL,
    reason       TEXT NOT NULL,
    detail       TEXT NOT NULL,
    state        TEXT NOT NULL,
    action_json  TEXT,
    handler      TEXT,
    created_at   BIGINT NOT NULL,
    updated_at   BIGINT NOT NULL,
    history_json TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_reports_reporter ON reports(reporter, created_at);
CREATE INDEX IF NOT EXISTS idx_reports_state ON reports(state, created_at);

CREATE TABLE IF NOT EXISTS content_media_refs (
    media_id   TEXT NOT NULL,
    ref_kind   TEXT NOT NULL,
    ref_id     TEXT NOT NULL,
    owner      TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (ref_kind, ref_id, media_id)
);

CREATE INDEX IF NOT EXISTS idx_cmr_media ON content_media_refs(media_id);

CREATE TABLE IF NOT EXISTS content_index (
    doc_id     TEXT PRIMARY KEY,
    kind       TEXT NOT NULL,
    owner      TEXT NOT NULL,
    audience   TEXT NOT NULL DEFAULT 'public',
    group_name TEXT NOT NULL DEFAULT '',
    title      TEXT NOT NULL DEFAULT '',
    body       TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_content_index_recent
    ON content_index(created_at DESC, doc_id DESC);
CREATE INDEX IF NOT EXISTS idx_content_index_kind
    ON content_index(kind, created_at DESC);


