-- M024 — PostgreSQL import compatibility backfill (G00-04 S4)
--
-- The 110-table SQLite snapshot exposed four shapes that M014 never covered:
--   * channel_role.role is TEXT in SQLite (owner/moderator/member/guest), not
--     a BIGINT enum, and carries granted_by / created_at;
--   * friend_tag, group_governance_audit and relations_audit had no PG landing
--     table at all.
--
-- This is an append-only forward fix: M014 remains untouched. Every statement
-- is re-runnable. Rollback: restore channel_role.role to BIGINT (lossy if text
-- roles already exist), then DROP the three new tables; dropping them discards
-- only rows imported after this migration.

BEGIN;

ALTER TABLE channel_role
    ALTER COLUMN role TYPE TEXT USING role::text;

ALTER TABLE channel_role
    ADD COLUMN IF NOT EXISTS granted_by TEXT NOT NULL DEFAULT '';

ALTER TABLE channel_role
    ADD COLUMN IF NOT EXISTS created_at BIGINT NOT NULL DEFAULT 0;

CREATE INDEX IF NOT EXISTS idx_channel_role_user
    ON channel_role(user_id, channel_id);

CREATE TABLE IF NOT EXISTS friend_tag (
    user_id    TEXT NOT NULL,
    friend_id  TEXT NOT NULL,
    tag        TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (user_id, friend_id, tag)
);

CREATE TABLE IF NOT EXISTS group_governance_audit (
    seq      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id TEXT NOT NULL,
    action   TEXT NOT NULL,
    actor    TEXT NOT NULL,
    reason   TEXT NOT NULL,
    trace    TEXT NOT NULL DEFAULT '',
    at       BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_group_gov_audit_group
    ON group_governance_audit(group_id, seq);

CREATE TABLE IF NOT EXISTS relations_audit (
    seq     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor   TEXT NOT NULL,
    subject TEXT NOT NULL,
    kind    TEXT NOT NULL,
    at      BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_ra_actor
    ON relations_audit(actor, seq);

COMMIT;
