//! G03-01: the normal-channel submit transaction.
//!
//! One SQLite transaction allocates the per-conversation seq, writes the
//! mailbox row, records the idempotency key and enqueues delivery tasks. A
//! retry with the same `(sender_device, idempotency_key)` returns the original
//! message and only fills recipients that are still missing.

use rusqlite::{params, OptionalExtension as _};

use super::{
    bump_change, channel_class_of, insert_mailbox_tx, next_seq_tx, touch_projection_tx, BodyKind,
    ChannelClass, MailError, MailInsert, MessageStore, OwnerType, Result,
};

/// Server-side default for the author recall window ("2 分钟内可撤回").
pub const RECALL_WINDOW_MS: u64 = 2 * 60 * 1000;

/// Membership as the social layer saw it. `joined_seq`/`left_seq` are
/// conversation seq positions, so the eligibility rule is independent of
/// wall-clock skew: a message with seq `s` reaches a member when
/// `joined_seq <= s` and (`left_seq` is absent or `s < left_seq`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SubmitRecipient {
    pub user_id: String,
    pub joined_seq: u64,
    pub left_seq: Option<u64>,
}

impl SubmitRecipient {
    /// A member with no join/leave edges (direct chats, long-standing members).
    pub fn member(user_id: &str) -> Self {
        Self {
            user_id: user_id.to_string(),
            joined_seq: 0,
            left_seq: None,
        }
    }

    pub fn joined(user_id: &str, joined_seq: u64) -> Self {
        Self {
            user_id: user_id.to_string(),
            joined_seq,
            left_seq: None,
        }
    }

    pub fn left(user_id: &str, joined_seq: u64, left_seq: u64) -> Self {
        Self {
            user_id: user_id.to_string(),
            joined_seq,
            left_seq: Some(left_seq),
        }
    }

    pub fn eligible_at(&self, seq: u64) -> bool {
        seq >= self.joined_seq && self.left_seq.is_none_or(|left| seq < left)
    }
}

/// Everything needed to submit one normal message. `msg_id` is generated by
/// the caller (the HTTP layer derives it from the idempotency key), which keeps
/// retries byte-identical.
pub struct SubmitRequest<'a> {
    pub owner: (OwnerType, &'a str),
    pub sender: &'a str,
    pub sender_device: &'a str,
    pub idempotency_key: &'a str,
    pub msg_id: &'a str,
    pub type_id: &'a str,
    pub payload: &'a str,
    pub body_kind: BodyKind,
    pub recipients: &'a [SubmitRecipient],
    pub forward_of: Option<&'a str>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum SubmitOutcome {
    Created {
        msg_id: String,
        seq: u64,
        recipients: usize,
    },
    /// Same device + idempotency key seen before. `recipients_added` counts
    /// newly enqueued (or re-armed) recipients.
    Duplicate {
        msg_id: String,
        seq: u64,
        recipients_added: usize,
    },
}

struct ExistingSubmit {
    conv_id: String,
    msg_id: String,
    seq: u64,
    payload_hash: String,
}

/// Content fingerprint used to reject "same key, different message" retries.
/// The device may regenerate `msg_id`; the payload must not change.
fn submit_fingerprint(
    conv_id: &str,
    type_id: &str,
    payload: &str,
    kind: BodyKind,
    forward_of: Option<&str>,
) -> String {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for part in [
        conv_id.as_bytes(),
        type_id.as_bytes(),
        kind.as_str().as_bytes(),
        payload.as_bytes(),
        forward_of.unwrap_or("").as_bytes(),
    ] {
        for byte in part {
            hash ^= *byte as u64;
            hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
        }
        hash ^= 0xff;
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("{hash:016x}")
}

impl MessageStore {
    /// messaging.send — one transaction, idempotent by
    /// `(sender_device, idempotency_key)`.
    ///
    /// The orchestrator only sequences: validate → look up the key → replay or
    /// insert → commit. Every step that can fail leaves the transaction
    /// uncommitted, so an abort cannot leave a half message behind.
    pub fn submit(&self, req: &SubmitRequest<'_>) -> Result<SubmitOutcome> {
        validate_submit(req)?;
        let (ot, oid) = (req.owner.0.as_str(), req.owner.1);
        let now = wxlike_core::types::now_ms();
        let fingerprint =
            submit_fingerprint(oid, req.type_id, req.payload, req.body_kind, req.forward_of);

        let mut conn = self.c();
        let tx = conn.transaction()?;
        if let Some(found) = lookup_submit(&tx, req)? {
            let outcome = replay_submit(&tx, &found, req, &fingerprint, now)?;
            tx.commit()?;
            return Ok(outcome);
        }
        let outcome = insert_submit(&tx, req, ot, oid, &fingerprint, now)?;
        tx.commit()?;
        Ok(outcome)
    }

    /// messaging.recall — same as [`MessageStore::withdraw`] but with the
    /// server-owned recall window. Administrators use `withdraw_as`, which is
    /// intentionally not time-limited (audited moderator path).
    pub fn recall_message(
        &self,
        owner: (OwnerType, &str),
        msg_id: &str,
        actor: &str,
    ) -> Result<()> {
        self.withdraw_within(owner, msg_id, actor, Some(RECALL_WINDOW_MS))
    }

    /// messaging.edit — author-only, optimistic on `edit_version`. The sealed
    /// body is stored verbatim; the server never synthesises plaintext.
    pub fn edit_message(
        &self,
        owner: (OwnerType, &str),
        msg_id: &str,
        actor: &str,
        expected_version: Option<u32>,
        payload: &str,
        body_kind: BodyKind,
    ) -> Result<u32> {
        if payload.is_empty() {
            return Err(MailError::InvalidInput("payload is empty"));
        }
        let (ot, oid) = (owner.0.as_str(), owner.1);
        let now = wxlike_core::types::now_ms();
        let mut conn = self.c();
        let tx = conn.transaction()?;
        let row: Option<(String, i64, i64)> = tx
            .query_row(
                "SELECT sender, edit_version, withdrawn FROM mailbox
                 WHERE owner_type = ?1 AND owner_id = ?2 AND msg_id = ?3",
                params![ot, oid, msg_id],
                |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?)),
            )
            .optional()?;
        let Some((sender, version, withdrawn)) = row else {
            return Err(MailError::EditRefused("unknown message"));
        };
        if sender != actor {
            return Err(MailError::EditRefused("not the author"));
        }
        if withdrawn != 0 {
            return Err(MailError::EditRefused("message recalled"));
        }
        let version = version as u32;
        if expected_version.is_some_and(|expected| expected != version) {
            return Err(MailError::EditRefused("edit version conflict"));
        }
        let next_version = version + 1;
        tx.execute(
            "UPDATE mailbox SET payload = ?4, body_kind = ?5, edit_version = ?6
             WHERE owner_type = ?1 AND owner_id = ?2 AND msg_id = ?3",
            params![
                ot,
                oid,
                msg_id,
                payload,
                body_kind.as_str(),
                next_version as i64
            ],
        )?;
        bump_change(&tx, ot, oid, msg_id, "edit", actor)?;
        // Re-projects the row only when it is the newest message; the preview
        // of an older edit is superseded by later traffic.
        super::refresh_projection_after_recall_tx(&tx, ot, oid, msg_id, now)?;
        tx.commit()?;
        Ok(next_version)
    }

    /// messaging.forward — copies a plain source row into a new message and
    /// records `forward_of`. Ciphertext sources are refused: the recipient may
    /// not hold a key for the original sender's seal, so forwarding sealed
    /// bodies is the client's re-encryption job, not the server's.
    #[allow(clippy::too_many_arguments)]
    pub fn forward_message(
        &self,
        owner: (OwnerType, &str),
        source_msg_id: &str,
        sender: &str,
        sender_device: &str,
        idempotency_key: &str,
        msg_id: &str,
        recipients: &[SubmitRecipient],
    ) -> Result<SubmitOutcome> {
        let (ot, oid) = (owner.0.as_str(), owner.1);
        let (type_id, payload, withdrawn, kind) = {
            let c = self.c();
            c.query_row(
                "SELECT type_id, payload, withdrawn, body_kind FROM mailbox
                 WHERE owner_type = ?1 AND owner_id = ?2 AND msg_id = ?3",
                params![ot, oid, source_msg_id],
                |r| {
                    Ok((
                        r.get::<_, String>(0)?,
                        r.get::<_, String>(1)?,
                        r.get::<_, i64>(2)? != 0,
                        r.get::<_, String>(3)?,
                    ))
                },
            )
            .optional()?
            .ok_or(MailError::ForwardRefused("source message not found"))?
        };
        if withdrawn {
            return Err(MailError::ForwardRefused("source message recalled"));
        }
        if BodyKind::parse(&kind) == Some(BodyKind::Ciphertext) {
            return Err(MailError::ForwardRefused(
                "ciphertext must be re-sealed by the client",
            ));
        }
        self.submit(&SubmitRequest {
            owner,
            sender,
            sender_device,
            idempotency_key,
            msg_id,
            type_id: &type_id,
            payload: &payload,
            body_kind: BodyKind::Plain,
            recipients,
            forward_of: Some(source_msg_id),
        })
    }

    /// Bounded queue depth (pending + in-flight), optionally per user.
    pub fn delivery_depth(&self, user: Option<&str>) -> Result<u64> {
        let c = self.c();
        let count: i64 = match user {
            Some(user) => c.query_row(
                "SELECT COUNT(*) FROM delivery_task
                  WHERE target_user = ?1 AND state IN ('pending', 'inflight')",
                params![user],
                |r| r.get(0),
            )?,
            None => c.query_row(
                "SELECT COUNT(*) FROM delivery_task
                  WHERE state IN ('pending', 'inflight')",
                [],
                |r| r.get(0),
            )?,
        };
        Ok(count as u64)
    }
}

fn check_forward_source(
    tx: &rusqlite::Transaction<'_>,
    ot: &str,
    oid: &str,
    source: &str,
) -> Result<()> {
    let row: Option<(i64, String)> = tx
        .query_row(
            "SELECT withdrawn, body_kind FROM mailbox
             WHERE owner_type = ?1 AND owner_id = ?2 AND msg_id = ?3",
            params![ot, oid, source],
            |r| Ok((r.get(0)?, r.get(1)?)),
        )
        .optional()?;
    let Some((withdrawn, kind)) = row else {
        return Err(MailError::ForwardRefused("source message not found"));
    };
    if withdrawn != 0 {
        return Err(MailError::ForwardRefused("source message recalled"));
    }
    if BodyKind::parse(&kind) == Some(BodyKind::Ciphertext) {
        return Err(MailError::ForwardRefused(
            "ciphertext must be re-sealed by the client",
        ));
    }
    Ok(())
}

/// Every input the submit transaction refuses before it touches any table.
fn validate_submit(req: &SubmitRequest<'_>) -> Result<()> {
    if req.sender_device.is_empty() {
        return Err(MailError::InvalidInput("sender_device is required"));
    }
    if req.idempotency_key.is_empty() {
        return Err(MailError::InvalidInput("idempotency_key is required"));
    }
    if req.msg_id.is_empty() {
        return Err(MailError::InvalidInput("msg_id is required"));
    }
    if req.payload.is_empty() {
        return Err(MailError::InvalidInput("payload is empty"));
    }
    if req.recipients.is_empty() {
        return Err(MailError::NoRecipients);
    }
    match channel_class_of(req.type_id) {
        Some(ChannelClass::Normal) => Ok(()),
        Some(ChannelClass::HighPriority) => Err(MailError::WrongChannel(
            req.type_id.to_string(),
            "high_priority",
        )),
        Some(ChannelClass::Ephemeral) => Err(MailError::WrongChannel(
            req.type_id.to_string(),
            "ephemeral",
        )),
        None => Err(MailError::UnregisteredType(req.type_id.to_string())),
    }
}

fn lookup_submit(
    tx: &rusqlite::Transaction<'_>,
    req: &SubmitRequest<'_>,
) -> Result<Option<ExistingSubmit>> {
    Ok(tx
        .query_row(
            "SELECT conv_id, msg_id, seq, payload_hash FROM message_submit
             WHERE sender_device = ?1 AND idempotency_key = ?2",
            params![req.sender_device, req.idempotency_key],
            |r| {
                Ok(ExistingSubmit {
                    conv_id: r.get(0)?,
                    msg_id: r.get(1)?,
                    seq: r.get::<_, i64>(2)? as u64,
                    payload_hash: r.get(3)?,
                })
            },
        )
        .optional()?)
}

/// A retry of a key we have already committed: return the original message and
/// only fill recipients that are still missing. Reusing the key for different
/// content is a client bug, not a retry — refuse instead of silently resending
/// the previous body.
fn replay_submit(
    tx: &rusqlite::Transaction<'_>,
    found: &ExistingSubmit,
    req: &SubmitRequest<'_>,
    fingerprint: &str,
    now: u64,
) -> Result<SubmitOutcome> {
    if found.conv_id != req.owner.1 || found.payload_hash != fingerprint {
        return Err(MailError::IdempotencyConflict(
            req.sender_device.to_string(),
        ));
    }
    let added = ensure_tasks(tx, &found.msg_id, found.seq, req.recipients, now)?;
    reset_hidden_for(tx, &found.conv_id, found.seq, req.recipients, now)?;
    Ok(SubmitOutcome::Duplicate {
        msg_id: found.msg_id.clone(),
        seq: found.seq,
        recipients_added: added,
    })
}

/// The first commit for this key: allocate the conversation seq, write the
/// timeline row, record the idempotency key, fan out delivery tasks and bump the
/// list projection — all inside the caller's transaction.
fn insert_submit(
    tx: &rusqlite::Transaction<'_>,
    req: &SubmitRequest<'_>,
    ot: &str,
    oid: &str,
    fingerprint: &str,
    now: u64,
) -> Result<SubmitOutcome> {
    if let Some(source) = req.forward_of {
        check_forward_source(tx, ot, oid, source)?;
    }
    let seq = next_seq_tx(tx, ot, oid)?;
    if !req
        .recipients
        .iter()
        .any(|recipient| recipient.eligible_at(seq))
    {
        return Err(MailError::NoRecipients);
    }
    let insert = MailInsert {
        owner_type: ot,
        owner_id: oid,
        seq,
        msg_id: req.msg_id,
        sender: req.sender,
        sender_device: req.sender_device,
        type_id: req.type_id,
        payload: req.payload,
        now_ms: now,
        body_kind: req.body_kind,
        edit_version: 0,
        forward_of: req.forward_of,
    };
    if !insert_mailbox_tx(tx, &insert)? {
        return Err(MailError::InvalidInput("msg_id already exists"));
    }
    record_key(tx, req, oid, seq, fingerprint, now)?;
    let added = ensure_tasks(tx, req.msg_id, seq, req.recipients, now)?;
    reset_hidden_for(tx, oid, seq, req.recipients, now)?;
    touch_projection_tx(
        tx,
        ot,
        oid,
        seq,
        req.sender,
        req.type_id,
        req.payload,
        req.body_kind,
        now,
    )?;
    Ok(SubmitOutcome::Created {
        msg_id: req.msg_id.to_string(),
        seq,
        recipients: added,
    })
}

/// Write the idempotency row. A collision here means another transaction won the
/// same key between our lookup and this insert: refuse, never double-send.
fn record_key(
    tx: &rusqlite::Transaction<'_>,
    req: &SubmitRequest<'_>,
    oid: &str,
    seq: u64,
    fingerprint: &str,
    now: u64,
) -> Result<()> {
    let res = tx.execute(
        "INSERT INTO message_submit(
             sender_device, idempotency_key, conv_id, msg_id, seq, payload_hash, created_at)
         VALUES(?1, ?2, ?3, ?4, ?5, ?6, ?7)",
        params![
            req.sender_device,
            req.idempotency_key,
            oid,
            req.msg_id,
            seq as i64,
            fingerprint,
            now as i64
        ],
    );
    match res {
        Ok(_) => Ok(()),
        Err(e) if super::is_unique(&e) => {
            Err(MailError::InvalidInput("idempotency key already used"))
        }
        Err(e) => Err(e.into()),
    }
}

/// Enqueue (or re-arm) one delivery task per eligible recipient. Socket writes
/// never remove rows; only a stored ack moves them to `stored` (G03-02).
fn ensure_tasks(
    tx: &rusqlite::Transaction<'_>,
    msg_id: &str,
    seq: u64,
    recipients: &[SubmitRecipient],
    now: u64,
) -> Result<usize> {
    let mut touched = 0usize;
    for recipient in recipients.iter().filter(|r| r.eligible_at(seq)) {
        touched += tx.execute(
            "INSERT OR IGNORE INTO delivery_task(
                 msg_id, target_user, target_device, state, attempts, next_at,
                 joined_seq, left_seq, created_at, updated_at)
             VALUES(?1, ?2, '*', 'pending', 0, ?3, ?4, ?5, ?3, ?3)",
            params![
                msg_id,
                recipient.user_id,
                now as i64,
                recipient.joined_seq as i64,
                recipient.left_seq.map(|v| v as i64)
            ],
        )?;
        // A retry of a previously dead/failed delivery re-arms it; stored and
        // in-flight rows are left alone.
        touched += tx.execute(
            "UPDATE delivery_task
                SET state = 'pending', lease_owner = NULL, lease_until = 0, next_at = ?3,
                    updated_at = ?3
              WHERE msg_id = ?1 AND target_user = ?2 AND target_device = '*'
                AND state IN ('failed', 'dead')",
            params![msg_id, recipient.user_id, now as i64],
        )?;
    }
    Ok(touched)
}

/// A new message resurrects a conversation the user had removed from the list.
fn reset_hidden_for(
    tx: &rusqlite::Transaction<'_>,
    conv_id: &str,
    seq: u64,
    recipients: &[SubmitRecipient],
    now: u64,
) -> Result<()> {
    for recipient in recipients.iter().filter(|r| r.eligible_at(seq)) {
        tx.execute(
            "UPDATE conversation_pref
                SET hidden = 0, version = version + 1, updated_at = ?3
              WHERE user_id = ?1 AND conv_id = ?2 AND hidden = 1",
            params![recipient.user_id, conv_id, now as i64],
        )?;
    }
    Ok(())
}
