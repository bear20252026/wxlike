//! Wire envelope, versioned so the protocol can evolve independently of storage.
//!
//! Version history:
//! * `1` — `conv_id / sender / to / seq / kind / body / sent_at_ms`
//! * `2` — adds `msg_id` (client-generated dedup key), `quote_of` (reply
//!   reference) and `receipt` (delivered/read ack), plus `MsgBody::Recall` and
//!   `MsgBody::Custom`.
//!
//! bincode encodes positionally, so appending fields is only half of
//! compatibility: [`Envelope::from_bytes`] also decodes the version-1 layout
//! explicitly and upgrades it (`msg_id` stays zero, which every consumer treats
//! as "absent"). New fields carry `#[serde(default)]` for the JSON paths.

use rand::RngCore as _;
use serde::{Deserialize, Serialize};

/// Current protocol version written by this build.
pub const PROTOCOL_VERSION: u8 = 2;

/// 16 random bytes generated by the sender; the global deduplication key.
pub type MsgId = [u8; 16];

/// The all-zero id: "no dedup key", i.e. a version-1 message.
pub const NO_MSG_ID: MsgId = [0u8; 16];

/// `MsgBody::Custom` kinds reserved by the task book (WP-04/06/08/09) plus the
/// P1 message-operation set (contract §3.5).
pub mod custom_kind {
    pub const MENTION: &str = "mention";
    pub const RTC_SIGNAL: &str = "rtc-signal";
    pub const WALLET_TRANSFER: &str = "wallet.transfer";
    pub const WALLET_REDPACKET: &str = "wallet.redpacket";
    pub const WALLET_CLAIM: &str = "wallet.redpacket.claim";
    /// Transient "X is typing…" signal: online-only, never persisted, never
    /// parked (the P3 `high_priority` channel; transitional handling in P1).
    pub const TYPING: &str = "typing";
    /// Single forwarded message; payload carries a snapshot of the original.
    pub const FORWARD: &str = "msg.forward";
    /// Merged forward of several messages in one bundle.
    pub const MERGE_FORWARD: &str = "msg.merge";
    /// Sealed 1:1 secret-chat payload (P1 E2EE wiring, ADR-1 optional mode).
    pub const E2EE_DM: &str = "e2ee.dm";
}

/// Serde adapter for JSON payloads inside a bincode frame.
///
/// bincode is not self-describing, so it cannot encode `serde_json::Value`
/// directly (`deserialize_any` is unsupported). The payload is carried as its
/// JSON text instead, which keeps the ergonomic `Value` API for feature code
/// and the compact positional wire format for the transport.
pub mod json_bytes {
    use serde::{de, Deserialize, Deserializer, Serializer};

    pub fn serialize<S>(value: &serde_json::Value, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: Serializer,
    {
        serializer.serialize_str(&value.to_string())
    }

    pub fn deserialize<'de, D>(deserializer: D) -> Result<serde_json::Value, D::Error>
    where
        D: Deserializer<'de>,
    {
        let text = String::deserialize(deserializer)?;
        serde_json::from_str(&text).map_err(de::Error::custom)
    }
}

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct Envelope {
    pub version: u8,
    pub conv_id: String,
    pub sender: String,
    /// Recipient user ids. Empty = conversation broadcast (delivery to all
    /// conversation members except the sender, once membership exists).
    #[serde(default)]
    pub to: Vec<String>,
    pub seq: u64,
    pub kind: MsgKind,
    pub body: MsgBody,
    /// millis since epoch, set by sender
    pub sent_at_ms: u64,
    /// Client-generated id; unique across the system, used for dedup, recall
    /// and receipts. Zero for legacy v1 messages.
    #[serde(default)]
    pub msg_id: MsgId,
    /// Message this envelope quotes (reply/reference).
    #[serde(default)]
    pub quote_of: Option<MsgId>,
    /// Delivery/read acknowledgement for `quote_of` (Delivered) or for the id
    /// carried in the variant (Read).
    #[serde(default)]
    pub receipt: Option<Receipt>,
}

#[derive(Serialize, Deserialize, Clone, Copy, Debug, PartialEq, Eq)]
pub enum MsgKind {
    Text,
    Blob,
    System,
}

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub enum MsgBody {
    Text(String),
    Bytes(Vec<u8>),
    Notice(String),
    /// "Un-send `target`": the peer replaces the message with a placeholder.
    Recall {
        target: MsgId,
    },
    /// Structured feature messages (mentions, call signaling, red packets).
    Custom {
        kind: String,
        #[serde(with = "json_bytes")]
        payload: serde_json::Value,
    },
}

#[derive(Serialize, Deserialize, Clone, Copy, Debug, PartialEq, Eq)]
pub enum Receipt {
    /// The referenced message reached the recipient's device.
    Delivered,
    /// Everything up to and including `up_to_msg_id` was read.
    Read { up_to_msg_id: MsgId },
}

/// The version-1 layout, kept private and only used to decode old bytes.
#[derive(Serialize, Deserialize)]
struct EnvelopeV1 {
    version: u8,
    conv_id: String,
    sender: String,
    #[serde(default)]
    to: Vec<String>,
    seq: u64,
    kind: MsgKind,
    body: MsgBody,
    sent_at_ms: u64,
}

impl Envelope {
    /// Fresh dedup id from the OS RNG.
    pub fn new_msg_id() -> MsgId {
        let mut id = [0u8; 16];
        rand::thread_rng().fill_bytes(&mut id);
        id
    }

    pub fn is_recall(&self) -> bool {
        matches!(self.body, MsgBody::Recall { .. })
    }

    /// Transient typing indicator (`Custom{kind:"typing"}`): delivered to
    /// online recipients only, never persisted or parked.
    pub fn is_typing(&self) -> bool {
        matches!(&self.body, MsgBody::Custom { kind, .. } if kind == custom_kind::TYPING)
    }

    /// The message this envelope refers to: recall target, quote, or the
    /// message a receipt acknowledges.
    pub fn refers_to(&self) -> Option<MsgId> {
        match &self.body {
            MsgBody::Recall { target } => Some(*target),
            _ => match self.receipt {
                Some(Receipt::Read { up_to_msg_id }) => Some(up_to_msg_id),
                _ => self.quote_of,
            },
        }
    }

    /// Conversation broadcast (no explicit recipients).
    pub fn text(
        conv_id: impl Into<String>,
        sender: impl Into<String>,
        seq: u64,
        text: impl Into<String>,
    ) -> Self {
        Self::direct(conv_id, sender, Vec::new(), seq, text)
    }

    /// Directed message: `to` lists recipient user ids.
    pub fn direct(
        conv_id: impl Into<String>,
        sender: impl Into<String>,
        to: Vec<String>,
        seq: u64,
        text: impl Into<String>,
    ) -> Self {
        Self::with_body(conv_id, sender, to, seq, MsgBody::Text(text.into()))
    }

    /// Builder used by every constructor: versioned, with a fresh dedup id.
    pub fn with_body(
        conv_id: impl Into<String>,
        sender: impl Into<String>,
        to: Vec<String>,
        seq: u64,
        body: MsgBody,
    ) -> Self {
        Self {
            version: PROTOCOL_VERSION,
            conv_id: conv_id.into(),
            sender: sender.into(),
            to,
            seq,
            kind: kind_of(&body),
            body,
            sent_at_ms: now_ms(),
            msg_id: Self::new_msg_id(),
            quote_of: None,
            receipt: None,
        }
    }

    /// `Recall` envelope for a message this sender previously sent.
    pub fn recall(conv_id: impl Into<String>, sender: impl Into<String>, target: MsgId) -> Self {
        let conv_id = conv_id.into();
        let sender = sender.into();
        Self::with_body(conv_id, sender, Vec::new(), 0, MsgBody::Recall { target })
    }

    /// Acknowledgement of this message, authored by `reader` and addressed back
    /// to the original sender. The reader must be named explicitly: the hub
    /// only accepts frames whose `sender` matches the bound connection, so an
    /// ack written in the author's name would be dropped as a forgery.
    pub fn receipt_from(&self, reader: impl Into<String>, receipt: Receipt) -> Self {
        let reader = reader.into();
        let mut env = Self::with_body(
            self.conv_id.clone(),
            reader,
            vec![self.sender.clone()],
            0,
            MsgBody::Notice(String::new()),
        );
        env.kind = MsgKind::System;
        env.quote_of = Some(self.msg_id);
        env.receipt = Some(receipt);
        env
    }

    pub fn quoted(mut self, msg_id: MsgId) -> Self {
        self.quote_of = Some(msg_id);
        self
    }

    pub fn to_bytes(&self) -> anyhow::Result<Vec<u8>> {
        Ok(bincode::serialize(self)?)
    }

    /// Decodes version-2 bytes, falling back to the version-1 layout.
    pub fn from_bytes(b: &[u8]) -> anyhow::Result<Self> {
        if let Ok(env) = bincode::deserialize::<Envelope>(b) {
            return Ok(env);
        }
        let old = bincode::deserialize::<EnvelopeV1>(b)?;
        Ok(Self {
            version: old.version,
            conv_id: old.conv_id,
            sender: old.sender,
            to: old.to,
            seq: old.seq,
            kind: old.kind,
            body: old.body,
            sent_at_ms: old.sent_at_ms,
            msg_id: NO_MSG_ID,
            quote_of: None,
            receipt: None,
        })
    }
}

/// `kind` stays derivable from the body so the two cannot disagree.
fn kind_of(body: &MsgBody) -> MsgKind {
    match body {
        MsgBody::Text(_) => MsgKind::Text,
        MsgBody::Bytes(_) | MsgBody::Recall { .. } => MsgKind::Blob,
        MsgBody::Notice(_) | MsgBody::Custom { .. } => MsgKind::System,
    }
}

pub fn now_ms() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

impl MsgBody {
    /// Placeholder body stored/returned in place of a recalled message.
    pub const RECALLED_TEXT: &'static str = "消息已撤回";

    pub fn recalled() -> Self {
        MsgBody::Notice(Self::RECALLED_TEXT.to_string())
    }

    /// The text a list/search result shows for this body ("preview line").
    ///
    /// Feature payloads (red packets, forwards…) get a human-readable tag
    /// instead of leaking their JSON; images show as `[图片]` like the
    /// mature clients do.
    pub fn preview_text(&self) -> String {
        match self {
            MsgBody::Text(t) => t.clone(),
            MsgBody::Bytes(_) => "[图片/媒体]".to_string(),
            MsgBody::Notice(n) => n.clone(),
            MsgBody::Recall { .. } => Self::RECALLED_TEXT.to_string(),
            MsgBody::Custom { kind, payload } => match kind.as_str() {
                custom_kind::WALLET_REDPACKET => "[红包]".to_string(),
                custom_kind::WALLET_TRANSFER => "[转账]".to_string(),
                custom_kind::WALLET_CLAIM => "[红包领取]".to_string(),
                custom_kind::FORWARD => format!(
                    "[转发] {}",
                    payload.get("text").and_then(|v| v.as_str()).unwrap_or("")
                ),
                custom_kind::MERGE_FORWARD => format!(
                    "[合并转发] {}",
                    payload.get("title").and_then(|v| v.as_str()).unwrap_or("")
                ),
                custom_kind::E2EE_DM => "[加密消息]".to_string(),
                other => format!("[{other}]"),
            },
        }
    }
}
