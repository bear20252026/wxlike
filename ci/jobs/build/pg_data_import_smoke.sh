#!/usr/bin/env bash
# G00-04 S4 data-import smoke: synthetic SQLite -> PostgreSQL public tables.
#
# Covers the four properties the cutover tool promises before touching a real
# database: parent-before-child order, NULL/empty separation, digest match,
# and a resumable re-load after a table is marked failed.

set -euo pipefail

: "${DATABASE_URL:?DATABASE_URL is required}"
SQLITE_FILE="$(mktemp /tmp/wxlike-data-import-XXXXXX.db)"
WORK_DIR="$(mktemp -d /tmp/wxlike-data-import-work-XXXXXX)"
trap 'rm -f "$SQLITE_FILE"; rm -rf "$WORK_DIR"' EXIT
printf '%s\n' '{"targets": {"ci_import_view_source": "ci_import_view"}}' > "$WORK_DIR/mapping.json"

python3 - "$SQLITE_FILE" <<'PY'
import sqlite3
import sys

conn = sqlite3.connect(sys.argv[1])
conn.executescript(
    """
    CREATE TABLE ci_import_parent (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL
    );
    CREATE TABLE ci_import_child (
        id TEXT PRIMARY KEY,
        parent_id TEXT NOT NULL REFERENCES ci_import_parent(id),
        body TEXT,
        n INTEGER NOT NULL
    );
    CREATE TABLE ci_import_serial (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        note TEXT
    );
    CREATE TABLE ci_import_empty (
        id TEXT PRIMARY KEY,
        note TEXT
    );
    CREATE TABLE ci_import_values (
        id TEXT PRIMARY KEY,
        payload BLOB,
        note TEXT,
        amount NUMERIC
    );
    CREATE TABLE ci_import_view_source (
        id TEXT PRIMARY KEY,
        label TEXT NOT NULL,
        extra TEXT NOT NULL DEFAULT ''
    );
    """
)
conn.execute("INSERT INTO ci_import_parent VALUES ('p1', 'one')")
conn.execute("INSERT INTO ci_import_parent VALUES ('p2', 'two')")
conn.execute("INSERT INTO ci_import_child VALUES ('c1', 'p1', NULL, 1)")
conn.execute("INSERT INTO ci_import_child VALUES ('c2', 'p2', '', 2)")
conn.execute("INSERT INTO ci_import_serial(note) VALUES ('first')")
conn.execute("INSERT INTO ci_import_serial(note) VALUES ('second')")
conn.execute(
    "INSERT INTO ci_import_values VALUES (?, ?, ?, ?)",
    ("v1", b"\x00\xff", "line1\r\nline2", 1.23),
)
conn.execute("INSERT INTO ci_import_values VALUES ('v2', NULL, '', 0.10)")
conn.execute("INSERT INTO ci_import_view_source VALUES ('e1', 'view label', 'view extra')")
conn.commit()
conn.close()
PY

psql -X "$DATABASE_URL" -v ON_ERROR_STOP=1 -q <<'SQL'
DROP VIEW IF EXISTS ci_import_view CASCADE;
DROP TABLE IF EXISTS ci_import_child, ci_import_parent, ci_import_serial,
    ci_import_empty, ci_import_values, ci_import_view_base CASCADE;
DELETE FROM import_run WHERE run_id = 'ci-import';
CREATE TABLE ci_import_parent (id TEXT PRIMARY KEY, name TEXT NOT NULL);
CREATE TABLE ci_import_child (
    id TEXT PRIMARY KEY,
    parent_id TEXT NOT NULL REFERENCES ci_import_parent(id),
    body TEXT,
    n BIGINT NOT NULL
);
CREATE TABLE ci_import_serial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note TEXT
);
CREATE TABLE ci_import_empty (id TEXT PRIMARY KEY, note TEXT);
CREATE TABLE ci_import_values (
    id TEXT PRIMARY KEY,
    payload BYTEA,
    note TEXT,
    amount NUMERIC(20, 2)
);
CREATE TABLE ci_import_view_base (
    id TEXT PRIMARY KEY,
    label TEXT NOT NULL,
    extra TEXT NOT NULL DEFAULT ''
);
CREATE VIEW ci_import_view AS
    SELECT id, label, extra FROM ci_import_view_base;
CREATE OR REPLACE FUNCTION ci_import_view_insert_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO ci_import_view_base (id, label, extra)
    VALUES (NEW.id, NEW.label, NEW.extra);
    RETURN NEW;
END $$;
CREATE OR REPLACE FUNCTION ci_import_view_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM ci_import_view_base WHERE id = OLD.id;
    RETURN OLD;
END $$;
CREATE TRIGGER ci_import_view_insert
    INSTEAD OF INSERT ON ci_import_view
    FOR EACH ROW EXECUTE FUNCTION ci_import_view_insert_fn();
CREATE TRIGGER ci_import_view_delete
    INSTEAD OF DELETE ON ci_import_view
    FOR EACH ROW EXECUTE FUNCTION ci_import_view_delete_fn();
INSERT INTO ci_import_view_base VALUES ('e0', 'old view', '');
INSERT INTO ci_import_parent VALUES ('p0', 'old');
INSERT INTO ci_import_child VALUES ('c0', 'p0', NULL, 0);
INSERT INTO ci_import_serial(note) VALUES ('old');
INSERT INTO ci_import_values VALUES ('v0', NULL, '', 0);
SQL

python3 composition/data-import/import_all.py \
    --sqlite "$SQLITE_FILE" \
    --dsn "$DATABASE_URL" \
    --work-dir "$WORK_DIR" \
    --mapping "$WORK_DIR/mapping.json" \
    --run-id ci-import \
    --max-window-seconds 120

psql -X "$DATABASE_URL" -v ON_ERROR_STOP=1 -q <<'SQL'
DO $$
BEGIN
    IF (SELECT count(*) FROM ci_import_parent) <> 2 THEN
        RAISE EXCEPTION 'data-import: parent rows';
    END IF;
    IF (SELECT count(*) FROM ci_import_child) <> 2 THEN
        RAISE EXCEPTION 'data-import: child rows';
    END IF;
    IF (SELECT count(*) FROM ci_import_serial) <> 2 THEN
        RAISE EXCEPTION 'data-import: serial rows';
    END IF;
    IF (SELECT count(*) FROM ci_import_empty) <> 0 THEN
        RAISE EXCEPTION 'data-import: empty table';
    END IF;
    IF (SELECT count(*) FROM ci_import_values) <> 2 THEN
        RAISE EXCEPTION 'data-import: value table';
    END IF;
    IF (SELECT count(*) FROM ci_import_view) <> 1 THEN
        RAISE EXCEPTION 'data-import: view rows';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM ci_import_view
        WHERE id = 'e1' AND label = 'view label' AND extra = 'view extra'
    ) THEN
        RAISE EXCEPTION 'data-import: view trigger did not fire';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM ci_import_values
        WHERE id = 'v1'
          AND payload = '\x00ff'::bytea
          AND note = E'line1\r\nline2'
          AND amount = 1.23
    ) THEN
        RAISE EXCEPTION 'data-import: bytea/CRLF/numeric value changed';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM ci_import_values
        WHERE id = 'v2' AND payload IS NULL AND note = '' AND amount = 0.10
    ) THEN
        RAISE EXCEPTION 'data-import: NULL/empty numeric value changed';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM import_run WHERE run_id = 'ci-import' AND status = 'verified'
    ) THEN
        RAISE EXCEPTION 'data-import: run not verified';
    END IF;
    IF EXISTS (
        SELECT 1 FROM import_table WHERE run_id = 'ci-import' AND status <> 'verified'
    ) THEN
        RAISE EXCEPTION 'data-import: not every table verified';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM ci_import_child WHERE id = 'c1' AND body IS NULL
    ) THEN
        RAISE EXCEPTION 'data-import: NULL body did not survive';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM ci_import_child WHERE id = 'c2' AND body = ''
    ) THEN
        RAISE EXCEPTION 'data-import: empty body did not survive';
    END IF;
END $$;
SQL

# Simulate an interrupted run: child rows are gone and the ledger says failed.
psql -X "$DATABASE_URL" -v ON_ERROR_STOP=1 -q <<'SQL'
DELETE FROM ci_import_child;
UPDATE import_table SET status = 'failed', error = 'smoke interruption'
WHERE run_id = 'ci-import' AND source_table = 'ci_import_child';
SQL

python3 composition/data-import/import_all.py \
    --sqlite "$SQLITE_FILE" \
    --dsn "$DATABASE_URL" \
    --work-dir "$WORK_DIR" \
    --mapping "$WORK_DIR/mapping.json" \
    --run-id ci-import \
    --resume \
    --max-window-seconds 120

psql -X "$DATABASE_URL" -v ON_ERROR_STOP=1 -q <<'SQL'
DO $$
DECLARE
    next_id BIGINT;
BEGIN
    IF (SELECT count(*) FROM ci_import_child) <> 2 THEN
        RAISE EXCEPTION 'data-import resume: child rows';
    END IF;
    INSERT INTO ci_import_serial(note) VALUES ('after resume') RETURNING id INTO next_id;
    IF next_id <> 3 THEN
        RAISE EXCEPTION 'data-import: sequence not reset, next id=%', next_id;
    END IF;
END $$;
SQL

echo "G00-04 data import smoke: OK"
